package com.braseiro.dnd5e.adventure;

import android.content.Context;
import com.braseiro.dnd5e.AppDb;
import com.braseiro.dnd5e.AppDbTestHelper;
import org.json.JSONArray;
import org.json.JSONObject;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.RobolectricTestRunner;
import org.robolectric.RuntimeEnvironment;
import org.robolectric.annotation.Config;

import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.UUID;
import static org.junit.Assert.*;

/**
 * P1 regression: execute all five Faerun campaigns through the player action
 * API to both terminal choices. Validate the persisted result after every
 * action, re-open the real SQLite database three times, and reject reward replay.
 * This tests executable consequences, not merely catalog JSON fields.
 */
@RunWith(RobolectricTestRunner.class)
@Config(sdk = 35, manifest = Config.NONE)
public final class FaerunCampaignEndingsRobolectricTest {
    @Test
    public void normalDndWorldAdapterDoesNotWriteMystaraProfile() throws Exception {
        Context context = RuntimeEnvironment.getApplication();
        String databaseName = "dnd_profile_isolation_" + UUID.randomUUID().toString().substring(0, 8) + ".db";
        AppDb db = AppDbTestHelper.createSandbox(context, databaseName);
        try {
            db.setActiveMapProfile("mystara");
            JSONObject before = db.getSceneState();
            AdventureNode target = FaerunAdventureModuleCatalog.byId("fraif_tomb_damara")
                    .getNode("scene_1");
            assertFalse("Normal D&D must never advance frozen Mystara world",
                    new AdventureWorldAdapter(db, null).applyNodeConsequences(target, new JSONObject()));
            JSONObject after = db.getSceneState();
            assertEquals(before.optString("location"), after.optString("location"));
            assertEquals(before.optInt("day_number"), after.optInt("day_number"));
        } finally {
            db.close();
            context.deleteDatabase(databaseName);
        }
    }

    @Test
    public void fiveCampaignsTwoEndingsAndThreeSqliteReopens() throws Exception {
        Context context = RuntimeEnvironment.getApplication();
        List<AdventureModule> modules = FaerunAdventureModuleCatalog.all();
        assertEquals(5, modules.size());
        int completed = 0;
        for (AdventureModule module : modules) {
            Set<String> endings = new HashSet<>();
            for (int endingChoice = 0; endingChoice < 2; endingChoice++) {
                String name = "faerun_endings_" + UUID.randomUUID().toString().substring(0, 8) + ".db";
                AppDb db = AppDbTestHelper.createSandbox(context, name);
                try {
                    db.setActiveMapProfile("dnd");
                    AdventureEngine engine = new AdventureEngine(db, null, null);
                    assertTrue(module.getId(), engine.loadOrStartAdventure(module, 91L)
                            .optBoolean("module_installed"));
                    // All current modules use setup, scene_1..scene_4, completed.
                    // Follow the principal route; only the terminal choice varies.
                    for (int step = 0; step < 5; step++) {
                        String before = engine.getActiveState().getCurrentNodeId();
                        AdventureNode current = module.getNode(before);
                        assertNotNull(module.getId() + "/" + before, current);
                        List<AdventureTransition> options = current.getTransitions();
                        int selection = step == 4 ? endingChoice : 0;
                        assertTrue(module.getId() + "/" + before, options.size() > selection);
                        AdventureTransition selected = options.get(selection);
                        JSONObject params = new JSONObject()
                                .put("target_node_id", selected.getTargetNodeId())
                                .put("roll", 20).put("modifier", 20);
                        int oldBranches = engine.getActiveState().getBranchHistory().length();
                        JSONObject action = engine.processAction(selected.getId(), params);
                        assertTrue(module.getId() + "/" + selected.getId() + ": " + action,
                                action.optBoolean("committed"));
                        assertFalse("Player rolls cannot be generated by the GM",
                                action.optBoolean("auto_rolls", false));
                        AdventureNode destination = module.getNode(selected.getTargetNodeId());
                        if (destination != null && !destination.getLocationId().isEmpty()) {
                            assertTrue("World location update failed: " + action,
                                    action.optBoolean("world_sync_ok"));
                            assertEquals("Adventure location must update the active D&D profile",
                                    destination.getLocationId(),
                                    db.getSceneState().optString("location"));
                        }
                        AdventureState stored = new AdventurePersistenceAdapter(db)
                                .loadState(module.getId(), 91L);
                        assertNotNull(stored);
                        assertEquals(selected.getTargetNodeId(), stored.getCurrentNodeId());
                        assertEquals(oldBranches + 1, stored.getBranchHistory().length());
                        JSONArray addedFlags = selected.getEffects().optJSONArray("add_flags");
                        if (addedFlags != null) {
                            for (int i = 0; i < addedFlags.length(); i++) {
                                assertTrue(module.getId() + ": missing saved choice effect",
                                        stored.hasFlag(addedFlags.getString(i)));
                            }
                        }
                    }
                    assertEquals("completed", engine.getActiveState().getStatus());
                    Set<String> finalFlags = new HashSet<>();
                    JSONArray flags = engine.getActiveState().toJson().getJSONArray("flags");
                    for (int i = 0; i < flags.length(); i++) finalFlags.add(flags.getString(i));
                    endings.add(finalFlags.toString());

                    for (int reopen = 0; reopen < 3; reopen++) {
                        db.close();
                        db = AppDbTestHelper.createSandbox(context, name);
                        AdventureEngine resumed = new AdventureEngine(db, null, null);
                        JSONObject result = resumed.loadOrStartAdventure(module, 91L);
                        assertEquals(module.getId() + " reopen #" + reopen,
                                "completed", result.optString("current_node_id"));
                        assertEquals("completed", resumed.getActiveState().getStatus());
                        assertEquals(5, resumed.getActiveState().getBranchHistory().length());
                        for (String flag : finalFlags) {
                            assertTrue("Lost durable effect after SQLite reopen: " + flag,
                                    resumed.getActiveState().hasFlag(flag));
                        }
                        JSONObject replay = resumed.processAction(
                                module.getNode("scene_4").getTransitions().get(endingChoice).getId(),
                                new JSONObject());
                        assertFalse("Completed adventures must reject duplicate awards",
                                replay.optBoolean("committed"));
                        assertEquals(5, resumed.getActiveState().getBranchHistory().length());
                    }
                    completed++;
                } finally {
                    if (db != null) db.close();
                    context.deleteDatabase(name);
                }
            }
            assertEquals(module.getId() + ": two terminal choices must persist different effects",
                    2, endings.size());
        }
        assertEquals(10, completed);
    }
}
