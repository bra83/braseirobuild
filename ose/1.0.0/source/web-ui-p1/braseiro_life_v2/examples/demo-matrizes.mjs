import {createLegacyStore,createLifeStore,transact,buildSceneContext} from '../src/index.mjs';
import {loadMatrixBundle} from '../src/node-matrices.mjs';
const bundle=await loadMatrixBundle('gurps-serial-killer');
let s=createLifeStore(createLegacyStore({system:'gurps',worldId:'cidade-marrone'}));
const dispatch=c=>s=transact(s,c,{verifiedByHost:true});
dispatch({id:'profile',type:'matrix_configure',packId:'gurps-serial-killer'});
dispatch({id:'capture',type:'event',event:{id:'capture',lifeCauseId:'cause-justice-1',summary:'Marrone capturou o criminoso, que continua preso.',actorIds:['marrone'],visibility:'private'}});
dispatch({id:'custody',type:'fact',key:'criminal-custody',value:'imprisoned',visibility:'gm_only'});
dispatch({id:'years',type:'advance',toDay:1096});
dispatch({id:'draw',type:'matrix_draw',bundle,context:{originEventId:'capture',characterId:'marrone',mode:'serial-killer',capabilities:['related_person','record_available','can_wait','previous_visit','home_exists','support_available']}});
const result=s.matrixHistory.at(-1).result;
console.log('Após três anos:',result.status);
console.log('Sugestão reservada:',result.proposal);
console.log('Antes da seleção pelo Mestre:',buildSceneContext(s,{actorIds:['marrone']}).offers.length,'ofertas públicas');
const offer=buildSceneContext(s,{actorIds:['marrone'],audience:'gm'}).offers[0];
if(offer)dispatch({id:'present',type:'matrix_present',offerId:offer.id});
console.log('Depois da seleção:',buildSceneContext(s,{actorIds:['marrone']}).offers);
console.log('Cânone preservado:',s.facts['criminal-custody'].value);
console.log('Cinco eixos auditados:',result.draws.filter(d=>d.accepted).length);
