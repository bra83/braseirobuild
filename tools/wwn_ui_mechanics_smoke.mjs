import fs from 'node:fs';
import { MemoryPersistenceAdapter } from '../app/src/main/assets/www/core/persistence-port.js';
import { makeEmptyCampaignState, serializeCampaignState } from '../app/src/main/assets/www/core/campaign-state.js';
import { createPartyState } from '../app/src/main/assets/www/core/party-state.js';
import { PlayerMechanicsFacade } from '../app/src/main/assets/www/core/player-mechanics-facade.js';

const assert=(value,message)=>{if(!value)throw new Error(message)};
const raw=JSON.parse(fs.readFileSync(new URL('../app/src/main/assets/www/data/wave6.iria.canonical.fixture.json',import.meta.url),'utf8'));
const character=structuredClone(raw);
delete character.fixtureKind;delete character.authority;delete character.evidencePolicy;
character.classId='FULL_EXPERT';
character.inventory=[];
character.silver=100;
character.copper=0;
const campaignId='ui-mechanics-smoke';
const persistence=new MemoryPersistenceAdapter();
const state=makeEmptyCampaignState({campaignId,displayName:'UI Mechanics Smoke',masterSeed:'ui-mechanics-smoke-seed'});
state.characterState=structuredClone(character);
state.charactersState={[character.characterId]:structuredClone(character)};
state.partyState=createPartyState({memberIds:[character.characterId],position:{q:0,r:0}});
state.npcState={bandit:{name:'Bandido de teste',hp:6,maxHp:6,meleeAC:10,rangedAC:10,save:15,skillBonus:1,attackBonus:1,damage:'1d6'}};
persistence.createCampaign({campaignId,displayName:state.displayName,stateJson:serializeCampaignState(state),masterSeed:state.rngState.masterSeed,rngAlgorithm:state.rngState.algorithm,initialSnapshotId:'snapshot:ui:r0'});
const ui=new PlayerMechanicsFacade({persistence});
const initial=ui.summary({campaignId});
assert(initial.status==='OK','summary must load');
assert(initial.character.name==='IRIA','canonical character projected');
assert(initial.inventory.weapons.some(w=>w.itemId==='UNARMED'),'unarmed attack always projected');
assert(initial.combat.enemies.some(e=>e.id==='bandit'),'live NPC projected');
const skill=ui.skillCheck({campaignId,skill:'Notice',attribute:'Wisdom',difficulty:8});
assert(skill.status==='OK','skill check must persist');
assert(Number.isInteger(skill.resolution.total),'skill result must have total');
assert(skill.summary.revision===1,'skill check must increment revision');
const save=ui.rollSave({campaignId,saveType:'MENTAL'});
assert(save.status==='OK','save must persist');
assert(save.summary.revision===2,'save must increment revision');
const attack=ui.attack({campaignId,npcId:'bandit',weaponId:'UNARMED'});
assert(attack.status==='OK','unarmed attack must resolve through certified combat service');
assert(attack.summary.revision===3,'attack must increment revision');
const final=persistence.loadCampaign(campaignId);
assert(final.status==='OK'&&final.revision===3,'canonical persisted revision must match UI facade');
const finalState=JSON.parse(final.stateJson);
assert(finalState.encounterState!=null,'mechanical state must be persisted');
console.log('WWN UI mechanics facade smoke: OK');
