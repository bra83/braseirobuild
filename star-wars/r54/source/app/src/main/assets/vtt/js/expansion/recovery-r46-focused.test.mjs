import assert from 'node:assert/strict';
import * as r from './recoveryExpansionRegistryR46.mjs';
let api=r.installRecoveryExpansionR46({});
assert.equal(api.coverage.fleet.mechanicalFleetAfter,114);
assert.equal(api.coverage.gadgets.mechanicsValidated,63);
let s=api.ensureInfra({credits:1000});
let a=api.beginAtomic(s,{id:'r46-1',type:'WORLD_EVENT',payload:{delta:5},expectedRevision:0,source:'BARBARA'});
assert.equal(a.transaction.status,'PREPARED');
let b=api.approveAtomic(a.state,a.transaction,{masterApproved:true});
assert.equal(b.transaction.status,'MASTER_APPROVED_CONTROLLER_PENDING');
let q=api.commitAtomic(b.state,b.transaction,{controllerId:'controller',apply:(z,p)=>{z.credits+=p.delta;return z}});
assert.equal(q.state.credits,1005); assert.equal(q.receipt.status,'COMMITTED');
let dup=api.commitAtomic(q.state,b.transaction,{controllerId:'controller'}); assert.equal(dup.duplicate,true);
let integ=api.integrity(q.state).report; assert.equal(integ.ok,true); assert.equal(integ.deadLetters,0);
let snap=api.snapshot(q.state,{reason:'R46'}); let restored=api.restoreSnapshot(snap.state,snap.snapshot); assert.equal(restored.credits,1005);
let backup=api.exportBackup(restored); let recovered=api.importBackup(backup); assert.equal(recovered.report.ok,true);
let e=api.ensureEconomy(recovered.state); e=api.registerAsset(e,{category:'vehicle',id:'test',profile:{price:100},ownerId:null});
let pp=api.proposePurchase(e,{category:'vehicle',assetId:'test',amount:100,ownerId:'party'}); assert.equal(pp.proposal.status,'PENDING_MASTER');
let mr=api.economyMasterResolve(pp.state,pp.proposal.id,{approved:true,masterId:'Barbara'}); assert.equal(mr.proposal.status,'MASTER_APPROVED_CONTROLLER_PENDING');
let cc=api.economyControllerCommit(mr.state,mr.proposal.id,{controllerId:'controller'}); assert.equal(cc.proposal.status,'COMMITTED'); assert.equal(cc.state.credits,905);
assert.equal(api.prepareVehicle('YT-1300 Light Freighter').status,'PREPARED');
assert.match(api.prepareVehicle('not-real').status,/FAIL_CLOSED/);
assert.equal(api.proposeAttachment('Gene-Lock').status,'PENDING_MASTER');
assert.match(api.proposeAttachment('not-real').status,/FAIL_CLOSED/);
